// TestEnrollCentralKeygen enrolls keys that certrally mock generates, over MAC-protected ir requests
// with and without --key-type and over signed cr and kur requests.
func TestEnrollCentralKeygen(t *testing.T) {
	useSecret(t, testSecret)
	m := startMock(t, "--listen", "127.0.0.1:0", "--ref", testRef)
	ca := &testCA{url: m.url}
	ecCert, ecKey := enrollIR(t, ca, "--subject", "CN=ec-device")
	rsaCert, rsaKey := enrollIR(t, ca, "--subject", "CN=rsa-device", "--key-type", "rsa-2048")

	tests := []struct {
		name       string
		args       []string
		wantKey    string
		wantLadder string
	}{
		{"CA choice", []string{"--ref", testRef}, "ECDSA P-256", "ip  accepted"},
		{"ecdsa-p384", []string{"--ref", testRef, "--key-type", "ecdsa-p384"}, "ECDSA P-384", "ip  accepted"},
		{"ed25519", []string{"--ref", testRef, "--key-type", "ed25519"}, "Ed25519", "ip  accepted"},
		{"ml-dsa-44", []string{"--ref", testRef, "--key-type", "ml-dsa-44"}, "ML-DSA-44", "ip  accepted"},
		{"composite", []string{"--ref", testRef, "--key-type", "mldsa65-ecdsa-p256-sha512"},
			"MLDSA65-ECDSA-P256-SHA512", "ip  accepted"},
		{"ml-kem-768", []string{"--ref", testRef, "--key-type", "ml-kem-768"}, "ML-KEM-768", "ip  accepted"},
		{"signed cr", []string{"--type", typeCR, "--cert", ecCert, "--key", ecKey, "--subject", "CN=cr",
			"--key-type", "ml-kem-1024"}, "ML-KEM-1024", "cp  accepted"},
		{"signed kur", []string{"--type", typeKUR, "--cert", rsaCert, "--key", rsaKey}, "ECDSA P-256", "kup  accepted"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			certOut, keyOut := filepath.Join(dir, "c.pem"), filepath.Join(dir, "k.pem")
			args := append([]string{"enroll", "--server", m.url, "--central-keygen",
				"--cert-out", certOut, "--key-out", keyOut}, tt.args...)
			code, out, errOut := run(t, args...)
			if code != exitOK {
				t.Fatalf("exited with %d:\n%s%s", code, out, errOut)
			}
			requireCertifiesKey(t, readCert(t, certOut), keyOut)
			for _, want := range []string{tt.wantKey, "Key generated by", "CN=Test KGA"} {
				if !strings.Contains(out, want) {
					t.Errorf("report lacks %q:\n%s", want, out)
				}
			}
			if !errorContains(errOut, tt.wantLadder) {
				t.Errorf("ladder lacks %q:\n%s", tt.wantLadder, errOut)
			}
			if !strings.Contains(m.stdout.String(), "generated  "+tt.wantKey+" key") {
				t.Errorf("the mock log does not note the %s key:\n%s", tt.wantKey, m.stdout)
			}
		})
	}
}

// TestEnrollCentralKeygenOutput checks the --json fields and that --out-format der writes the key the
// CA generated as DER PKCS#8.
func TestEnrollCentralKeygenOutput(t *testing.T) {
	useSecret(t, testSecret)
	m := startMock(t, "--listen", "127.0.0.1:0", "--ref", testRef)
	dir := t.TempDir()
	certOut, keyOut := filepath.Join(dir, "c.der"), filepath.Join(dir, "k.der")
	code, out, errOut := run(t, "enroll", "--server", m.url, "--ref", testRef, "--central-keygen",
		"--out-format", "der", "--cert-out", certOut, "--key-out", keyOut, "--json")
	if code != exitOK {
		t.Fatalf("exited with %d:\n%s%s", code, out, errOut)
	}
	var doc struct {
		Result enrollJSON `json:"result"`
	}
	if err := json.Unmarshal([]byte(out), &doc); err != nil {
		t.Fatal(err)
	}
	if !doc.Result.CentralKeyGeneration || doc.Result.KeyGenerationAuthority != "CN=Test KGA" {
		t.Errorf("centralKeyGeneration = %v, keyGenerationAuthority = %q", doc.Result.CentralKeyGeneration,
			doc.Result.KeyGenerationAuthority)
	}
	der, err := os.ReadFile(keyOut)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := x509.ParsePKCS8PrivateKey(der); err != nil {
		t.Errorf("the key file is not DER PKCS#8: %v", err)
	}
	certDER, err := os.ReadFile(certOut)
	if err != nil {
		t.Fatal(err)
	}
	cert, err := x509.ParseCertificate(certDER)
	if err != nil {
		t.Fatal(err)
	}
	requireCertifiesKey(t, cert, keyOut)
}

// TestEnrollCentralKeygenUsage checks the command lines that cannot ask for central key generation.
// None of them reaches the CA.
func TestEnrollCentralKeygenUsage(t *testing.T) {
	useSecret(t, testSecret)
	m := startMock(t, "--listen", "127.0.0.1:0", "--ref", testRef)
	edCert, edKey := enrollIR(t, &testCA{url: m.url}, "--key-type", "ed25519")
	kemCert, kemKey := filepath.Join(t.TempDir(), "kem.pem"), filepath.Join(t.TempDir(), "kem.key")
	ca := startCA(t, nil)
	dir := t.TempDir()
	key, csr := filepath.Join(dir, "k.pem"), filepath.Join(dir, "a.csr")
	if code, _, errOut := run(t, "keygen", "--out", filepath.Join(dir, "a.key"), "--csr-out", csr,
		"--subject", "CN=a"); code != exitOK {
		t.Fatalf("keygen exited with %d:\n%s", code, errOut)
	}

	tests := []struct {
		name string
		args []string
		want string
	}{
		{"p10cr", []string{"--ref", testRef, "--type", typeP10CR, "--key-out", key}, "needs --type ir, cr or kur"},
		{"p10cr with csr", []string{"--ref", testRef, "--type", typeP10CR, "--csr", csr}, "needs --type ir, cr or kur"},
		{"new key", []string{"--ref", testRef, "--new-key", filepath.Join(dir, "a.key")}, "--new-key cannot be used"},
		{"pop", []string{"--ref", testRef, "--pop", popChallenge, "--key-out", key}, "needs no proof of possession"},
		{"no key-out", []string{"--ref", testRef}, "--key-out is required"},
		{"unknown key type", []string{"--ref", testRef, "--key-type", "dsa-1024", "--key-out", key}, "unknown key type"},
		{"Ed25519 protection", []string{"--type", typeCR, "--cert", edCert, "--key", edKey, "--key-out", key},
			"which an Ed25519 key cannot decrypt"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			args := append([]string{"enroll", "--server", ca.url, "--central-keygen",
				"--cert-out", filepath.Join(dir, "c.pem")}, tt.args...)
			code, _, errOut := run(t, args...)
			if code != exitLocal || !errorContains(errOut, tt.want) {
				t.Errorf("exited with %d, want 1 and %q in:\n%s", code, tt.want, errOut)
			}
		})
	}
	if n := ca.requests.Load(); n != 0 {
		t.Errorf("the CA received %d requests", n)
	}
	// The protection key must also be able to decrypt when it was generated with the key type.
	code, out, errOut := run(t, "enroll", "--server", m.url, "--ref", testRef, "--subject", "CN=kem",
		"--key-type", "ml-kem-768", "--central-keygen", "--cert-out", kemCert, "--key-out", kemKey)
	if code != exitOK {
		t.Fatalf("exited with %d:\n%s%s", code, out, errOut)
	}
	code, _, errOut = run(t, "enroll", "--server", m.url, "--type", typeCR, "--cert", kemCert, "--key", kemKey,
		"--central-keygen", "--cert-out", filepath.Join(dir, "x.pem"), "--key-out", filepath.Join(dir, "x.key"))
	if code != exitLocal || !errorContains(errOut, "an ML-KEM-768 key cannot sign") {
		t.Errorf("exited with %d, want 1 and the key refused:\n%s", code, errOut)
	}
}

// TestEnrollCentralKeygenNotSupported checks the report of a CA that does not generate keys.
func TestEnrollCentralKeygenNotSupported(t *testing.T) {
	useSecret(t, testSecret)
	ca := startCA(t, nil)
	dir := t.TempDir()
	keyOut := filepath.Join(dir, "k.pem")
	code, out, errOut := run(t, "enroll", "--server", ca.url, "--ref", testRef, "--central-keygen",
		"--cert-out", filepath.Join(dir, "c.pem"), "--key-out", keyOut)
	if code != exitRejected || !errorContains(out+errOut, pkicmp.FailBadCertTemplate.String()) {
		t.Errorf("exited with %d, want %d with badCertTemplate:\n%s%s", code, exitRejected, out, errOut)
	}
	if _, err := os.Stat(keyOut); !os.IsNotExist(err) {
		t.Errorf("a key file was written: %v", err)
	}
}

// TestEnrollCentralKeygenUnconfirmed checks that the key the CA generated is saved with the
// certificate when the confirmation fails.
func TestEnrollCentralKeygenUnconfirmed(t *testing.T) {
	useSecret(t, testSecret)
	mock, err := mockserver.New(map[string][]byte{testRef: []byte(testSecret)}, slog.New(slog.DiscardHandler))
	if err != nil {
		t.Fatal(err)
	}
	srv := server.NewCAServer(unconfirmingCA{mock}, server.LightweightPolicy(),
		server.WithSigner(mock.Key(), mock.Cert()),
		server.WithSecretLookup(mock),
		server.WithCentralKeyGeneration(mockKeyGenerator{}, mock.KGAKey(), mock.KGACert()),
	)
	if err := srv.Err(); err != nil {
		t.Fatal(err)
	}
	ts := httptest.NewServer(srv)
	t.Cleanup(ts.Close)
	dir := t.TempDir()
	certOut, keyOut := filepath.Join(dir, "c.pem"), filepath.Join(dir, "k.pem")
	code, out, errOut := run(t, "enroll", "--server", ts.URL, "--ref", testRef, "--central-keygen",
		"--key-type", "ml-kem-768", "--cert-out", certOut, "--key-out", keyOut)
	if code != exitUnconfirmed {
		t.Fatalf("exited with %d, want %d:\n%s%s", code, exitUnconfirmed, out, errOut)
	}
	requireCertifiesKey(t, readCert(t, certOut), keyOut)
}

// TestPollCentralKeygen collects a waiting certificate with the key the CA generated, into the file
// enroll named and into the file --key-out names.
func TestPollCentralKeygen(t *testing.T) {
	useSecret(t, testSecret)
	m := startMock(t, "--listen", "127.0.0.1:0", "--ref", testRef, "--waiting", "1", "--check-after", "0s")
	t.Chdir(t.TempDir())
	later := func(name string, extra ...string) string {
		t.Helper()
		args := append([]string{"enroll", "--server", m.url, "--ref", testRef, "--subject", "CN=" + name,
			"--central-keygen", "--cert-out", name + ".pem", "--poll-later", "--capture", name + ".jsonl"}, extra...)
		code, out, errOut := run(t, args...)
		if code != exitOK || !strings.Contains(out, "Request waiting for the CA") {
			t.Fatalf("enroll exited with %d:\n%s%s", code, out, errOut)
		}
		return transactionIDIn(t, out)
	}

	id := later("saved", "--key-out", "saved.key", "--key-type", "ecdsa-p384")
	if _, err := os.Stat("saved.key"); !os.IsNotExist(err) {
		t.Errorf("enroll wrote the key before the CA sent it: %v", err)
	}
	code, out, errOut := run(t, "poll", "--transaction-id", id, "--capture", "saved.jsonl")
	if code != exitOK || !strings.Contains(out, "Key generated by") {
		t.Fatalf("poll exited with %d:\n%s%s", code, out, errOut)
	}
	requireCertifiesKey(t, readCert(t, "saved.pem"), "saved.key")
	if got := keyDescription(t, "saved.key"); got != "ECDSA P-384" {
		t.Errorf("key = %s, want ECDSA P-384", got)
	}

	id = later("moved", "--key-out", "moved.key")
	code, out, errOut = run(t, "poll", "--transaction-id", id, "--capture", "moved.jsonl", "--key-out", "other.key")
	if code != exitOK {
		t.Fatalf("poll --key-out exited with %d:\n%s%s", code, out, errOut)
	}
	requireCertifiesKey(t, readCert(t, "moved.pem"), "other.key")
	if _, err := os.Stat("moved.key"); !os.IsNotExist(err) {
		t.Errorf("poll wrote the file enroll named: %v", err)
	}

	// A request whose key the client generated has no key to save.
	code, out, errOut = run(t, "enroll", "--server", m.url, "--ref", testRef, "--subject", "CN=ec",
		"--cert-out", "ec.pem", "--key-out", "ec.key", "--poll-later", "--capture", "ec.jsonl")
	if code != exitOK {
		t.Fatalf("enroll exited with %d:\n%s%s", code, out, errOut)
	}
	code, _, errOut = run(t, "poll", "--transaction-id", transactionIDIn(t, out), "--capture", "ec.jsonl",
		"--key-out", "x.key")
	if code != exitLocal || !errorContains(errOut, "--key-out is only used") {
		t.Errorf("exited with %d:\n%s", code, errOut)
	}
}

// keyDescription names the algorithm of the private key in a file.
func keyDescription(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	key, err := keys.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	return keys.Describe(keys.Public(key))
}

// TestEnrollWizardCentralKeygen checks that the wizard leaves the key type to the CA and keeps
// --central-keygen in the printed command.
func TestEnrollWizardCentralKeygen(t *testing.T) {
	useSecret(t, testSecret)
	m := startMock(t, "--listen", "127.0.0.1:0", "--ref", testRef)
	t.Chdir(t.TempDir())
	a := useWizard(t, map[string]string{
		"CA certificate":      "",
		"Request":             keep,
		"Subject":             keep,
		"Alternative names":   "",
		"Save certificate to": keep,
		"Save private key to": keep,
		"Send the request?":   "yes",
	})
	code, _, errOut := run(t, "enroll", "--interactive", "--server", m.url, "--ref", testRef, "--central-keygen")
	if code != exitOK {
		t.Fatalf("enroll exited with %d:\n%s", code, errOut)
	}
	if got := a.shown["Key type"]; got != "chosen by the CA" {
		t.Errorf("shown key type = %q", got)
	}
	want := "certrally enroll --server " + m.url + " --ref " + testRef + " --subject CN=" + testRef +
		" --central-keygen --cert-out " + testRef + ".pem --key-out " + testRef + ".key"
	if command := printedCommand(t, errOut); command != want {
		t.Errorf("printed command\n%s\nwant\n%s", command, want)
	}
	requireCertifiesKey(t, readCert(t, testRef+".pem"), testRef+".key")
}
